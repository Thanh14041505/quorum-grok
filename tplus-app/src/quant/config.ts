export function regimeBucket(
  regime: string,
): "bull" | "sideways" | "bear" | "panic" {
  if (regime === "STRONG_BULL" || regime === "BULL") return "bull";
  if (regime === "SIDEWAYS") return "sideways";
  if (regime === "STRONG_BEAR") return "panic";
  return "bear";
}
